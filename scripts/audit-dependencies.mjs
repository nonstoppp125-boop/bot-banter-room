import fs from "node:fs";
import path from "node:path";
import ts from "typescript";

const root = process.cwd();
const manifest = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const lock = JSON.parse(fs.readFileSync(path.join(root, "package-lock.json"), "utf8"));
const direct = { ...manifest.dependencies, ...manifest.devDependencies };
const sourceFiles = [];
const configFiles = [
  "vite.config.ts", "vitest.config.ts", "eslint.config.js", "tsconfig.json", "src/styles.css",
  "wrangler.json", "bunfig.toml", "components.json", ".github/workflows/build.yml",
  ".github/workflows/deploy.yml", ".github/dependabot.yml"
];

function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (/\.(?:[cm]?[jt]sx?)$/.test(entry.name)) sourceFiles.push(full);
  }
}
walk(path.join(root, "src"));

const imports = new Map();
const configMentions = new Map();
const packageRoot = (specifier) => {
  if (specifier.startsWith(".") || specifier.startsWith("/") || specifier.startsWith("@/")) return null;
  const parts = specifier.split("/");
  return specifier.startsWith("@") ? parts.slice(0, 2).join("/") : parts[0];
};
const add = (map, key, file) => {
  if (!map.has(key)) map.set(key, new Set());
  map.get(key).add(path.relative(root, file).replaceAll(path.sep, "/"));
};

for (const file of sourceFiles) {
  const text = fs.readFileSync(file, "utf8");
  const kind = file.endsWith(".tsx") ? ts.ScriptKind.TSX : file.endsWith(".jsx") ? ts.ScriptKind.JSX : file.endsWith(".js") || file.endsWith(".mjs") || file.endsWith(".cjs") ? ts.ScriptKind.JS : ts.ScriptKind.TS;
  const ast = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, kind);
  const inspectModule = (node) => {
    if (node && ts.isStringLiteralLike(node)) {
      const pkg = packageRoot(node.text);
      if (pkg && Object.hasOwn(direct, pkg)) add(imports, pkg, file);
    }
  };
  const visit = (node) => {
    if (ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) inspectModule(node.moduleSpecifier);
    if (ts.isImportEqualsDeclaration(node) && ts.isExternalModuleReference(node.moduleReference)) inspectModule(node.moduleReference.expression);
    if (ts.isCallExpression(node)) {
      if (node.expression.kind === ts.SyntaxKind.ImportKeyword) inspectModule(node.arguments[0]);
      if (ts.isIdentifier(node.expression) && node.expression.text === "require") inspectModule(node.arguments[0]);
    }
    ts.forEachChild(node, visit);
  };
  visit(ast);
}
for (const relative of configFiles) {
  const file = path.join(root, relative);
  if (!fs.existsSync(file)) continue;
  const text = fs.readFileSync(file, "utf8");
  for (const pkg of Object.keys(direct)) {
    const escaped = pkg.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    if (new RegExp(escaped).test(text)) add(configMentions, pkg, file);
  }
}
for (const [name, command] of Object.entries(manifest.scripts ?? {})) {
  for (const pkg of Object.keys(direct)) {
    const bin = pkg.startsWith("@") ? pkg.split("/")[1] : pkg;
    if (new RegExp("(^|[^a-zA-Z0-9_-])" + bin.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "([^a-zA-Z0-9_-]|$)").test(command)) {
      add(configMentions, pkg, path.join(root, "package.json"));
    }
  }
}

const versions = new Map();
for (const [entry, value] of Object.entries(lock.packages ?? {})) {
  const marker = "node_modules/";
  const index = entry.lastIndexOf(marker);
  if (index < 0) continue;
  const suffix = entry.slice(index + marker.length);
  const parts = suffix.split("/");
  const name = suffix.startsWith("@") ? parts.slice(0, 2).join("/") : parts[0];
  if (!versions.has(name)) versions.set(name, new Set());
  versions.get(name).add(value.version ?? "(unknown)");
}
const duplicates = [...versions].filter(([, values]) => values.size > 1).sort((a,b)=>a[0].localeCompare(b[0]));
const directRows = Object.keys(direct).sort().map((name) => {
  const source = imports.get(name)?.size ?? 0;
  const config = configMentions.get(name)?.size ?? 0;
  const status = source ? "static import observed" : config ? "config/script mention only" : "no static/config reference found — manual review required";
  return { name, kind: Object.hasOwn(manifest.dependencies ?? {}, name) ? "runtime" : "development", source, config, versions: [...(versions.get(name) ?? [])].sort().join(", "), status };
});
const lines = [
  "# Static dependency usage inventory",
  "",
  "Generated by scripts/audit-dependencies.mjs from tracked source/config files. This is a static heuristic, not proof that an unreferenced package is safe to remove; dynamic loading, package side effects, generated tooling and ecosystem conventions require manual review.",
  "",
  `- Runtime direct dependencies: ${Object.keys(manifest.dependencies ?? {}).length}`,
  `- Development direct dependencies: ${Object.keys(manifest.devDependencies ?? {}).length}`,
  `- Source files scanned: ${sourceFiles.length}`,
  `- Lockfile package names with multiple resolved versions: ${duplicates.length}`,
  "",
  "## Direct dependency usage",
  "",
  "| Package | Kind | Source import files | Config/script files | Resolved versions | Static classification |",
  "|---|---|---:|---:|---|---|",
  ...directRows.map((r) => `| ${r.name} | ${r.kind} | ${r.source} | ${r.config} | ${r.versions || "not in lockfile"} | ${r.status} |`),
  "",
  "## Multiple resolved versions",
  "",
  "| Package | Versions |",
  "|---|---|",
  ...duplicates.map(([name, values]) => `| ${name} | ${[...values].sort().join(", ")} |`),
  "",
  "## Interpretation",
  "",
  "- Multiple resolved versions are transitive version multiplicities; they are not automatically duplicate direct dependencies or removable packages.",
  "- Packages with no static/config reference are review candidates only. Do not remove them without checking scripts, peer dependencies, CSS imports, dynamic imports and framework plugin discovery.",
  "- This report does not replace npm audit, license review, maintenance review or runtime tests.",
  ""
];
const report = lines.join("\n");
const output = process.argv[2];
if (output) fs.writeFileSync(output, report);
console.log(report);
