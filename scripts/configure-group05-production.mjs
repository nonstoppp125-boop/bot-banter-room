import fs from "node:fs";
import path from "node:path";
const [configPath]=process.argv.slice(2);
if(!configPath)throw new Error("Usage: node scripts/configure-group05-production.mjs <generated-wrangler-config>");
for(const key of ["CLOUDFLARE_D1_DATABASE_NAME","CLOUDFLARE_D1_DATABASE_ID"])if(!process.env[key]?.trim())throw new Error("Missing required environment variable: "+key);
if(!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(process.env.CLOUDFLARE_D1_DATABASE_ID))throw new Error("D1 database ID is invalid.");
if(!/^[a-zA-Z0-9_-]{1,64}$/.test(process.env.CLOUDFLARE_D1_DATABASE_NAME))throw new Error("D1 database name is invalid.");
const config=JSON.parse(fs.readFileSync(configPath,"utf8"));
const bindings=Array.isArray(config.d1_databases)?config.d1_databases:[];
config.d1_databases=bindings.filter(item=>item.binding!=="ACTION_DB");
const migrationDir=path.relative(path.dirname(path.resolve(configPath)),path.resolve("migrations/group05")).split(path.sep).join("/");
const resolved=path.resolve(path.dirname(path.resolve(configPath)),migrationDir);
if(resolved!==path.resolve("migrations/group05")||!fs.statSync(resolved).isDirectory())throw new Error("Migration directory is not the isolated Group 05 directory.");
const files=fs.readdirSync(resolved).filter(name=>name.endsWith(".sql"));
if(files.length!==1||files[0]!=="0005_memory_foundation.sql")throw new Error("Unexpected Group 05 migration files.");
config.d1_databases.push({binding:"ACTION_DB",database_name:process.env.CLOUDFLARE_D1_DATABASE_NAME,database_id:process.env.CLOUDFLARE_D1_DATABASE_ID,migrations_dir:migrationDir});
fs.writeFileSync(configPath,JSON.stringify(config,null,2)+"\n");
console.log("Configured ACTION_DB with the isolated Group 05 migration. Password authentication uses GitHub Actions secrets at runtime.");
